"""Roman-Hinglish captions for the DcPharma reel, timed to the user's Tia VO.

faster-whisper (projects/2026-10-datacenter-pharma/vo_words.json) heard the read in Devanagari and misheard some words,
but every script line is there in order. Each caption below is a Roman chunk from VO.md plus the range of whisper word
indices it covers, so the times are the real spoken times and the text is the script's.
"Pharma mein" was not in the whisper list; its time (34.10-34.72) comes from a word-timestamp pass on the 33.3-35.3 s
clip plus the energy envelope (silence 33.85-34.05, onset 34.1, "20" from 34.85).

usage: python3 scripts/captions_dcpharma.py
writes src/projects/dcpharma/captions.json and deliverables/2026-10-datacenter-pharma/subtitles.srt
"""
import json, os, re

W = json.load(open("projects/2026-10-datacenter-pharma/vo_words.json"))
TL = json.load(open("src/projects/dcpharma/timeline.json"))
EXTRA = {"pm": (34.10, 34.72)}  # "Pharma mein"
FIX_START = {85: 34.85}  # "बीस" (20): whisper put it at 34.54, inside "Pharma mein"

# (caption text, first whisper index, last whisper index) or (text, extra key)
CAPS = [
    ("Saalon se crash ka", 0, 2), ("wait kar rahe the na?", 3, 6),
    ("Is saal Nifty", 7, 9), ("peak se 16% gira", 10, 14),
    ("Ab kharidna kya hai?", 15, 18),
    ("Do themes ki demand", 19, 22), ("market ke mood pe", 23, 26), ("nahi chalti", 27, 28),
    ("Data centres:", 29, 30), ("vacancy sirf 2.8%", 31, 36),
    ("Pharma index:", 37, 38), ("ek saal mein", 39, 41), ("double digit upar", 42, 44),
    ("Par stock immune", 45, 47), ("nahi hota", 48, 49),
    ("Anant Raj March tak", 50, 52), ("peak se 40% neeche tha", 53, 58),
    ("Isliye theme ki", 59, 62), ("layer dekho", 63, 64),
    ("Zameen: Anant Raj", 65, 66), ("aur Lodha", 67, 68),
    ("Server: Netweb", 69, 70), ("62% revenue", 71, 73), ("AI systems se", 74, 77),
    ("Cooling: Blue Star", 78, 79), ("Naye orders", 80, 81), ("zyada tar data centres se", 82, 84),
    ("Pharma mein", "pm"), ("20 March ko", 85, 87), ("semaglutide ka patent", 88, 90), ("khatam hua", 91, 92),
    ("Agle din se", 93, 95), ("Natco, Zydus samet", 96, 98), ("10 companies ke", 99, 101), ("generic aane lage", 102, 104),
    ("Novo ne daam", 105, 107), ("48% tak kaat diye", 108, 112),
    ("Patent khulte hi", 113, 115), ("race shuru hoti hai", 116, 119), ("aur daam girte hain", 120, 123),
    ("Tum kaunsi layer", 124, 126), ("dekh rahe ho?", 127, 129), ("Comment karo", 130, 131),
]

assert len(W) == 132
covered = sorted(i for c in CAPS if len(c) == 3 for i in range(c[1], c[2] + 1))
assert covered == list(range(132)), "every whisper word must belong to exactly one caption"

caps = []
for c in CAPS:
    if len(c) == 2:
        s, e = EXTRA[c[1]]
    else:
        s, e = FIX_START.get(c[1], W[c[1]]["s"]), W[c[2]]["e"]
    text = re.sub(r"\.(?!\d)", "", c[0])  # house rule: no full stops on screen (decimal points stay)
    assert 2 <= len(text.split()) <= 5, text
    caps.append({"text": text, "s": round(s, 2), "e": round(e, 2)})

# show slightly before the word, hold through short gaps, never past the VO end
for i, c in enumerate(caps):
    c["show"] = round(max(0.0, c["s"] - 0.06), 2)
for i, c in enumerate(caps):
    nxt = caps[i + 1]["show"] if i + 1 < len(caps) else None
    c["hide"] = round(nxt if nxt is not None and nxt - c["e"] < 0.6 else c["e"] + 0.25, 2)
caps[-1]["hide"] = round(min(caps[-1]["e"] + 0.2, TL["beats"][-1]["start"]), 2)  # off before the end card

json.dump({"_note": "Generated by scripts/captions_dcpharma.py from vo_words.json + VO.md. show/hide are on-screen times.", "captions": caps},
          open("src/projects/dcpharma/captions.json", "w"), indent=1, ensure_ascii=False)


def ts(x):
    ms = int(round(x * 1000)); h, ms = divmod(ms, 3600000); m, ms = divmod(ms, 60000); s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


os.makedirs("deliverables/2026-10-datacenter-pharma", exist_ok=True)
with open("deliverables/2026-10-datacenter-pharma/subtitles.srt", "w") as f:
    for i, c in enumerate(caps, 1):
        f.write(f"{i}\n{ts(c['show'])} --> {ts(c['hide'])}\n{c['text']}\n\n")
for c in caps:
    words = len(c["text"].split()); dur = c["hide"] - c["show"]
    print(f"{c['show']:6.2f}-{c['hide']:6.2f} ({dur:4.2f}s, {words / dur:4.1f} w/s) {c['text']}")
